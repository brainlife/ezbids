#!/usr/bin/env python3
"""Generate draft brainlife datatypes for BIDS raw-data types that have no brainlife datatype.

For every raw-data (datatype, suffix) pair in the BIDS schema (rules.files.raw) that has no
active/planned row in data/bids_brainlife_map.yaml, write
``<out>/neuro.<datatype>.<suffix lowercased>.json`` (warehouse ``Datatypes`` shape) and
refresh the ``status: draft`` rows of the YAML (with --write-yaml; otherwise printed).

Output is deterministic (sorted keys, stable order): regenerating produces no diff.

Rules
- Files: one entry per BIDS extension of the pair (union over the schema groups). ``id`` is
  the extension without dots/slash, dots as underscores (``nii_gz``, ``ome_zarr``);
  ``filename`` is ``<suffix><ext>``; extensions ending in "/" are directories (``dirname``).
  Wildcard (``.*``) and bare ``/`` extensions are skipped: they name no concrete file.
- Formats: non-sidecar extensions (sidecars: ``.json``, ``.bval``, ``.bvec``) are grouped into
  alternative data formats; FORMAT_GROUPS members are one format (.nii.gz/.nii; BrainVision
  .vhdr+.eeg+.vmrk; EEGLAB .set+.fdt), any other extension is a format of its own.
- Required: one format -> its first extension is required (e.g. .nii.gz). Several formats
  (alternatives such as .edf or .bdf, or NIfTI or OME-Zarr) -> NONE required, and desc/readme
  say "Exactly one of: ... must be present". Only sidecars (e.g. coordsystem) -> the first.
- ``.json`` is required when schema.required_sidecar_fields finds unconditional required
  metadata for the pair (rules.sidecars, decidable selectors only); otherwise optional.
- ``bids.maps`` identity-maps every file; ``json: <suffix>.json`` is set on the main file of
  each data format whenever a .json extension exists.
- readme lists the other raw suffixes of the same BIDS datatype as related, separate datatypes.
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from aimport.brainlife_map import load_rows, row_covers  # noqa: E402
from aimport.schema import DEFAULT_SCHEMA, load_schema  # noqa: E402

DATA = Path(__file__).resolve().parents[1] / "src" / "aimport" / "data"
DEFAULT_YAML = DATA / "bids_brainlife_map.yaml"
DEFAULT_OUT = DATA / "datatype_drafts"
BIDS_VERSION = "1.11.2"
SIDECARS = {".json", ".bval", ".bvec"}
# Extensions that together make ONE data format (compressed/uncompressed, multi-file).
FORMAT_GROUPS = [
    [".nii.gz", ".nii"],
    [".vhdr", ".eeg", ".vmrk"],  # BrainVision
    [".set", ".fdt"],  # EEGLAB
]
BEGIN = "  # --- draft datatypes (generated by tools/draft_datatypes.py; do not edit) ---\n"
END = "  # --- end draft datatypes ---\n"

README = """# {name}

DRAFT — generated from BIDS v{ver} by aimport/tools/draft_datatypes.py; check the brainlife registry for an existing datatype before registering.

Uses BIDS as the datatype: files are named as in BIDS, BIDS datatype `{dt}`, suffix `{suffix}`.

Source: BIDS specification v{ver}, raw data, `{dt}/*_{suffix}`.

{notes}"""


def draft_name(datatype: str, suffix: str) -> str:
    return f"neuro/{datatype}/{suffix.lower()}"


def check_collisions(pairs) -> None:
    seen: dict[str, tuple[str, str]] = {}
    for pair in pairs:
        name = draft_name(*pair)
        if name in seen and seen[name] != pair:
            raise ValueError(f"draft names collide: {seen[name]} and {pair} both give {name}")
        seen[name] = pair


def _file_id(ext: str) -> str:
    return ext.strip("/").lstrip(".").replace(".", "_")


def formats(exts: list[str]) -> list[list[str]]:
    """Group the non-sidecar extensions into alternative data formats (schema order).

    Members of one FORMAT_GROUPS entry (compressed/uncompressed NIfTI, the BrainVision
    triplet, EEGLAB .set + .fdt) are one format; every other extension is a format of its own.
    """
    out: dict[tuple, list[str]] = {}
    for ext in exts:
        if ext not in SIDECARS:
            key = next((tuple(g) for g in FORMAT_GROUPS if ext in g), (ext,))
            out.setdefault(key, []).append(ext)
    return list(out.values())


def _format_label(fmt: list[str]) -> str:
    sep = " or " if fmt[0] in (".nii.gz", ".nii") else " + "
    return sep.join(e.rstrip("/") for e in fmt)


def build_draft(schema, datatype: str, suffix: str, extensions: list[str],
                related: list[str] | None = None) -> dict:
    exts = [e for e in extensions if e not in ("/", ".*")]
    fmts = formats(exts)
    data_exts = [e for f in fmts for e in f]
    multi = len(fmts) > 1
    # Required: a single-format suffix requires the first member of its format; with several
    # alternative formats nothing is required (exactly one of them must be present). If there
    # are only sidecars, the first is required.
    required = set() if multi else {fmts[0][0]} if fmts else {exts[0]}
    sidecar = [f for e in (data_exts or exts) for f in schema.required_sidecar_fields(datatype, suffix, e)]
    if ".json" in exts and sidecar:
        required.add(".json")
    mains = {f[0] for f in fmts}
    files, maps = [], []
    for ext in exts:
        entry = {"id": _file_id(ext), "desc": f"BIDS {suffix}{ext}", "ext": ext.rstrip("/"),
                 "required": ext in required}
        target = suffix + ext.rstrip("/")
        entry["dirname" if ext.endswith("/") else "filename"] = target
        files.append(entry)
        m = {"src": target, "dest": target}
        if ext in mains and ".json" in exts:
            m["json"] = f"{suffix}.json"
        maps.append(m)
    name = draft_name(datatype, suffix)
    desc = schema.suffix_description(suffix) or f"BIDS {datatype} {suffix}"
    notes = ""
    if multi:
        labels = [_format_label(f) for f in fmts]
        notes += (f"Exactly one of: {'; '.join(labels)} must be present"
                  " (alternative data formats, none is marked required).\n\n")
        desc += f" Exactly one of: {'; '.join(labels)} must be present."
    if ".json" in required and sidecar:
        notes += "The JSON sidecar is required (the schema requires metadata fields in it).\n\n"
    if related:
        notes += (f"Related BIDS files in `{datatype}/` (separate datatypes, not part of this one): "
                  + ", ".join(f"`{r}`" for r in related) + ".\n\n")
    return {
        "name": name,
        "desc": desc,
        "readme": README.format(name=name, ver=BIDS_VERSION, dt=datatype, suffix=suffix, notes=notes),
        "files": files,
        "datatype_tags": [],
        "bids": {"derivatives": datatype, "maps": maps},
        "draft": True,
        "bids_version": BIDS_VERSION,
    }


def _yaml_rows(drafts: list[dict]) -> str:
    out = [BEGIN]
    for d in drafts:
        fname = d["name"].replace("/", ".") + ".json"
        out.append(
            f"  - bids: {{datatype: {d['bids']['derivatives']}, suffix: {d['_suffix']}}}\n"
            f"    brainlife: {{datatype: {d['name']}, tags: []}}\n"
            f"    status: draft\n"
            f"    ref: datatype_drafts/{fname}\n"
        )
    out.append(END)
    return "".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--yaml", type=Path, default=DEFAULT_YAML)
    ap.add_argument("--write-yaml", action="store_true", help="refresh the draft rows in --yaml")
    args = ap.parse_args(argv)

    schema = load_schema(args.schema)
    rows = [r for r in load_rows(args.yaml) if r["status"] != "draft"]
    all_pairs = schema.raw_pairs()
    todo = {
        pair: exts for pair, exts in sorted(all_pairs.items())
        if not any(row_covers(r, *pair) for r in rows)
    }
    check_collisions(todo)

    args.out.mkdir(parents=True, exist_ok=True)
    keep = set()
    drafts = []
    for (datatype, suffix), exts in todo.items():
        related = sorted({sfx for (dt, sfx) in all_pairs if dt == datatype and sfx != suffix})
        d = build_draft(schema, datatype, suffix, exts, related)
        fname = d["name"].replace("/", ".") + ".json"
        keep.add(fname)
        (args.out / fname).write_text(
            json.dumps(d, indent=4, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")
        drafts.append({**d, "_suffix": suffix})
    for stale in args.out.glob("*.json"):
        if stale.name not in keep:
            stale.unlink()

    block = _yaml_rows(drafts)
    if args.write_yaml:
        text = args.yaml.read_text()
        pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        if pattern.search(text):
            text = pattern.sub(lambda _: block, text)
        else:
            text = text.replace("\n# BIDS datatypes with no", "\n" + block + "\n# BIDS datatypes with no", 1)
        args.yaml.write_text(text)
    else:
        print(block, end="")
    print(f"{len(drafts)} drafts in {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
